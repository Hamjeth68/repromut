"""Write e2/RESULTS-REPORT.md from the final analysis JSON and the case records (numbers are never typed by hand).

Usage: python e2/harness/make_report.py <results_dir> <analysis.json> <out.md>
"""
import json
import sys
from pathlib import Path

from repromut.stats import wilson


def pct(k, n):
    return f"{k}/{n}" + (f" ({100 * k / n:.0f}%)" if n else "")


def ci(lo, hi):
    return f"[{100 * lo:+.0f}, {100 * hi:+.0f}] pp" if lo == lo else "n/a"


def main(d, aj, out):
    A = json.loads(Path(aj).read_text())
    P, C = A["primary"], A["auditors_counts"]
    bases, cases = {}, []
    for f in sorted(Path(d).glob("*.jsonl")):
        for line in f.read_text().splitlines():
            r = json.loads(line)
            (bases.__setitem__(r["repo"], r) if r["case_id"] == "baseline" else cases.append(r))
    excluded = sorted(p.name.split(".")[0].replace("__", "/") for p in Path(d).glob("*.install_failure.txt"))
    L = []
    w = L.append
    w("# E2 results report\n")
    w("**Status: fully executed and analysed (local).** Protocol registered at commit `5dbf087` (public). "
      "All deviations are listed in `DEVIATIONS.md` (S1–S16 before registration, D1–D14 after). Generated by `e2/harness/make_report.py`.\n")
    w("## Verdict on H1 (pre-registered decision rule, section 9)\n")
    w(f"**{P['verdict'].upper()}.** Minimum evidence requires ≥12 `stable_change` positives from ≥4 repositories and ≥35 negatives; "
      f"observed **{P['n_pos']} positives from {P['n_pos_repos']} repositories and {P['n_neg']} negatives**. "
      "Under the registered rules, no confirmatory claim that dynamic re-execution is superior can be made.\n")
    w("Descriptively, every result-changing hidden-state mutation that was observed was detected by re-execution and by none of the declared-configuration comparisons:\n")
    w("| Auditor | Recall on positives | False alarms on negatives |")
    w("|---|---|---|")
    names = {"D": "D: dynamic re-execution (k=2)", "S1": "S1: declared-configuration static", "S2": "S2: extended manifest static",
             "C1": "C1 = S1 or D", "C2": "C2 = S2 or D"}
    for a in ("D", "S1", "S2", "C1", "C2"):
        (rk, rn), (fk, fn) = C[a]["recall"], C[a]["false_alarms"]
        w(f"| {names[a]} | {pct(rk, rn)} | {pct(fk, fn)} |")
    w("")
    w(f"Paired recall difference D − S1 = {100 * P['recall_diff']:.0f} pp, repository-cluster bootstrap 95% CI {ci(*P['recall_diff_ci'])}; "
      f"FPR(D) − FPR(S1) = {100 * P['fpr_diff']:.1f} pp, CI {ci(*P['fpr_diff_ci'])}; exact McNemar p (positives) = {P['mcnemar_p_pos']:.3g}. "
      f"False-alarm rule used: {P['fpr_rule']} (acceptable: {P['fpr_acceptable']}). These intervals are descriptive here, because the minimum-evidence condition failed.\n")
    w("## Repositories\n")
    w("| Repository | Baseline (5 runs) | Cases run | Stable changes | Notes |")
    w("|---|---|---|---|---|")
    for repo in sorted(bases):
        b = bases[repo]
        rc = [r for r in cases if r["repo"] == repo]
        sc = sum(r["label"] == "stable_change" for r in rc)
        st = "stable" if b["stable"] else ("all " + b["statuses"][0] if len(set(b["statuses"])) == 1 and b["statuses"][0] != "ok" else "nondeterministic")
        notes = []
        if b["statuses"][0] == "timeout": notes.append("exceeds 10-min limit")
        if b["statuses"][0] == "crash": notes.append("repository crashes as declared")
        labs = sorted({r['label'] for r in rc if r['label'] not in ('stable_change', 'unchanged')})
        if labs: notes.append("other labels: " + ", ".join(labs))
        w(f"| {repo} | {st} | {sum(r.get('d_reason') != 'not_run' for r in rc)} | {sc} | {'; '.join(notes)} |")
    for repo in excluded:
        w(f"| {repo} | — | 0 | 0 | install_failure: declared pins unsatisfiable on Python 3.10 |")
    w("")
    w("## Labels by case family\n")
    w("| Intent:family | Labels |")
    w("|---|---|")
    for k, v in sorted(A["labels_by_family"].items()):
        w(f"| {k} | " + ", ".join(f"{a}: {b}" for a, b in sorted(v.items())) + " |")
    w("\n## Pre-declared sensitivity analyses (section 11, D13, author check)\n")
    w("| Analysis | Positives | Negatives | Recall D | Recall S1 | FPR D | Verdict |")
    w("|---|---|---|---|---|---|---|")
    for k, v in A["sensitivity"].items():
        if "verdict" in v:
            w(f"| {k} | {v['n_pos']} | {v['n_neg']} | {v['recall_D']:.2f} | {v['recall_S1']:.2f} | {v['fpr_D']:.3f} | {v['verdict']} |")
        else:
            w(f"| {k} | " + ", ".join(f"{a}={b:.2f}" for a, b in v.items() if b is not None) + " | | | | | |")
    n = P["n_neg"]
    fk = C["D"]["false_alarms"][0]
    lo, hi = wilson(fk, n)
    w(f"\nWilson 95% interval for FPR(D): {fk}/{n} → [{100 * lo:.1f}%, {100 * hi:.1f}%].\n")
    Path(out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(*sys.argv[1:4])
